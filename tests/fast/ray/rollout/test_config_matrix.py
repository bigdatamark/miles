# [MODULE DOC]
# Tests of resolving the sglang configuration from run args. Covers the three resolution paths
# (default single model, prefill server count, yaml file with one or several models), server group
# worker type validation, inference of the weight-update flag from model paths, and detection of
# prefill/decode disaggregation at model and config level. Yaml cases write a config file into a
# temporary directory; run args come from the shared conftest helpers.
from __future__ import annotations

import pydantic
import pytest
from tests.fast.ray.rollout.conftest import make_args, make_sglang_config_yaml

from miles.backends.sglang_utils.sglang_config import resolve_sglang_config

# ----------------------------- resolve_sglang_config matrix -----------------------------


def _resolve_yaml(tmp_path, yaml_text: str, **args_overrides):
    # [FUNCTION DOC] HELPER: Writes the given yaml text to a config file in the temporary directory,
    # builds run args pointing the sglang config option at that file (plus any overrides), and returns
    # the resolved sglang config.
    cfg_path = tmp_path / "config.yaml"
    cfg_path.write_text(yaml_text)
    return resolve_sglang_config(make_args(sglang_config=str(cfg_path), **args_overrides))


class TestResolveSglangConfigPaths:
    # [CLASS DOC] Checks each way the resolver can build a config: from defaults, from a prefill
    # server count, and from a yaml file (single model and multi-model).
    def test_default_path_when_no_yaml_or_prefill(self):
        # [FUNCTION DOC] With eight rollout gpus, no yaml and no prefill server count, asserts the
        # config has exactly one model named default whose first server group is a regular worker, and
        # that the gpus of all groups sum to eight.
        args = make_args(rollout_num_gpus=8, sglang_config=None, prefill_num_servers=None)
        cfg = resolve_sglang_config(args)
        assert len(cfg.models) == 1
        assert cfg.models[0].name == "default"
        assert cfg.models[0].server_groups[0].worker_type == "regular"
        assert sum(g.num_gpus for m in cfg.models for g in m.server_groups) == 8

    def test_prefill_num_servers_path(self):
        # [FUNCTION DOC] With eight gpus, one gpu per engine, four prefill servers and no yaml, asserts
        # the single model has two server groups whose sorted worker types are decode and prefill.
        args = make_args(
            rollout_num_gpus=8,
            rollout_num_gpus_per_engine=1,
            prefill_num_servers=4,
            sglang_config=None,
        )
        cfg = resolve_sglang_config(args)
        # Two groups: prefill + decode
        groups = cfg.models[0].server_groups
        assert len(groups) == 2
        worker_types = sorted(g.worker_type for g in groups)
        assert worker_types == ["decode", "prefill"]

    def test_yaml_path_actor_only(self, tmp_path):
        # [FUNCTION DOC] Writes a yaml generated by the conftest helper for a model named actor, resolves
        # it with eight rollout gpus, and asserts one model named actor.
        cfg_path = tmp_path / "actor.yaml"
        cfg_path.write_text(make_sglang_config_yaml(name="actor"))
        args = make_args(sglang_config=str(cfg_path), rollout_num_gpus=8)
        cfg = resolve_sglang_config(args)
        assert len(cfg.models) == 1
        assert cfg.models[0].name == "actor"

    def test_yaml_path_multi_model_actor_plus_reference(self, tmp_path):
        # [FUNCTION DOC] Resolves a yaml with an actor model (eight gpus, weight updates on) and a
        # reference model (four gpus, weight updates off, own model path); the total of twelve gpus
        # must equal the rollout gpu count. Asserts model names in order (actor, ref) and that the
        # server group gpus sum to twelve.
        # 8 gpu actor + 4 gpu ref = 12 → must match args.rollout_num_gpus
        cfg = _resolve_yaml(
            tmp_path,
            "sglang:\n"
            "  - name: actor\n"
            "    update_weights: true\n"
            "    server_groups:\n"
            "      - worker_type: regular\n"
            "        num_gpus: 8\n"
            "        num_gpus_per_engine: 1\n"
            "  - name: ref\n"
            "    update_weights: false\n"
            "    model_path: /ref/model\n"
            "    server_groups:\n"
            "      - worker_type: regular\n"
            "        num_gpus: 4\n"
            "        num_gpus_per_engine: 1\n",
            rollout_num_gpus=12,
        )
        assert [m.name for m in cfg.models] == ["actor", "ref"]
        assert sum(g.num_gpus for m in cfg.models for g in m.server_groups) == 12


# ----------------------------- server group validation matrix ---------------


class TestServerGroupValidation:
    # [CLASS DOC] Checks validation of the worker type field of yaml server groups.
    def test_invalid_worker_type_raises(self, tmp_path):
        # [FUNCTION DOC] Resolves a yaml whose only server group has an unknown worker type; expects a
        # pydantic validation error whose message names the location of that field (first server
        # group, worker type).
        """An unknown worker_type is rejected while parsing, by name."""
        with pytest.raises(pydantic.ValidationError, match="server_groups.0.worker_type"):
            _resolve_yaml(
                tmp_path,
                "sglang:\n"
                "  - name: actor\n"
                "    server_groups:\n"
                "      - worker_type: invalid\n"
                "        num_gpus: 8\n",
                rollout_num_gpus=8,
            )

    @pytest.mark.parametrize("wt", ["regular", "prefill", "decode", "placeholder"])
    def test_all_valid_worker_types_accepted(self, wt, tmp_path):
        # [FUNCTION DOC] Parametrized over regular, prefill, decode and placeholder. Resolves a
        # one-group yaml with that worker type and eight gpus and asserts the parsed group keeps it.
        """Every documented worker_type parses through the yaml path."""
        cfg = _resolve_yaml(
            tmp_path,
            f"sglang:\n  - name: actor\n    server_groups:\n      - worker_type: {wt}\n        num_gpus: 8\n",
            rollout_num_gpus=8,
        )
        assert cfg.models[0].server_groups[0].worker_type == wt


class TestResolveDefaults:
    # [CLASS DOC] Checks how the weight-update flag of a model is defaulted from the model path and
    # the trained checkpoint path in the run args, and that an explicit value always wins.
    def test_resolve_explicit_update_weights_not_overridden(self, tmp_path):
        # [FUNCTION DOC] A model whose path equals the trained checkpoint but which explicitly sets
        # weight updates off must stay off after resolution.
        """An explicit update_weights is parsed verbatim even when the paths match."""
        cfg = _resolve_yaml(
            tmp_path,
            "sglang:\n"
            "  - name: ref\n"
            "    model_path: /actor/model\n"
            "    update_weights: false\n"
            "    server_groups:\n"
            "      - worker_type: regular\n"
            "        num_gpus: 8\n",
            rollout_num_gpus=8,
            hf_checkpoint="/actor/model",
        )
        assert cfg.models[0].update_weights is False

    def test_a_model_serving_the_trained_checkpoint_receives_weight_updates(self, tmp_path):
        # [FUNCTION DOC] A model with no explicit weight-update flag whose model path equals the
        # trained checkpoint path must resolve to weight updates on.
        """Left unset this is inferred from the paths, and inferring False for the actor trains
        against a frozen policy behind nothing louder than a warning."""
        cfg = _resolve_yaml(
            tmp_path,
            "sglang:\n"
            "  - name: actor\n"
            "    model_path: /actor/model\n"
            "    server_groups:\n"
            "      - worker_type: regular\n"
            "        num_gpus: 8\n",
            rollout_num_gpus=8,
            hf_checkpoint="/actor/model",
        )
        assert cfg.models[0].update_weights is True

    def test_a_model_serving_another_checkpoint_is_left_frozen(self, tmp_path):
        # [FUNCTION DOC] A model with no explicit weight-update flag whose model path differs from the
        # trained checkpoint path must resolve to weight updates off.
        """Inferring True for a reference model would let weight sync overwrite the frozen
        baseline the KL term is measured against."""
        cfg = _resolve_yaml(
            tmp_path,
            "sglang:\n"
            "  - name: ref\n"
            "    model_path: /ref/model\n"
            "    server_groups:\n"
            "      - worker_type: regular\n"
            "        num_gpus: 8\n",
            rollout_num_gpus=8,
            hf_checkpoint="/actor/model",
        )
        assert cfg.models[0].update_weights is False


# ----------------------------- has_pd_disaggregation aggregation -----------------


class TestPdDisaggregation:
    # [CLASS DOC] Checks the prefill/decode disaggregation flags on a resolved model and on the whole
    # config.
    def test_pd_detected_with_prefill(self, tmp_path):
        # [FUNCTION DOC] A model with one prefill group and one decode group (four gpus each) must
        # report prefill/decode disaggregation.
        """A prefill/decode split marks the model as PD-disaggregated."""
        cfg = _resolve_yaml(
            tmp_path,
            "sglang:\n"
            "  - name: x\n"
            "    server_groups:\n"
            "      - worker_type: prefill\n"
            "        num_gpus: 4\n"
            "      - worker_type: decode\n"
            "        num_gpus: 4\n",
            rollout_num_gpus=8,
        )
        assert cfg.models[0].has_pd_disaggregation is True

    def test_no_pd_for_pure_regular(self, tmp_path):
        # [FUNCTION DOC] A model with a single regular group must not report disaggregation.
        """Regular-only groups do not count as PD disaggregation."""
        cfg = _resolve_yaml(
            tmp_path,
            "sglang:\n  - name: x\n    server_groups:\n      - worker_type: regular\n        num_gpus: 8\n",
            rollout_num_gpus=8,
        )
        assert cfg.models[0].has_pd_disaggregation is False

    def test_sglang_config_aggregates_across_models(self, tmp_path):
        # [FUNCTION DOC] Two models of four gpus each: one with a regular group, the other (weight
        # updates off) with a prefill group. The config-level flag must be on because one model is
        # disaggregated.
        """One PD model makes the whole config PD-disaggregated."""
        cfg = _resolve_yaml(
            tmp_path,
            "sglang:\n"
            "  - name: a\n"
            "    server_groups:\n"
            "      - worker_type: regular\n"
            "        num_gpus: 4\n"
            "  - name: b\n"
            "    update_weights: false\n"
            "    server_groups:\n"
            "      - worker_type: prefill\n"
            "        num_gpus: 4\n",
            rollout_num_gpus=8,
        )
        assert cfg.has_pd_disaggregation is True
