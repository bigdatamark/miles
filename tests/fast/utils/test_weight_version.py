# [MODULE DOC] Unit tests for the weight version sanity helpers: validating that sample weight
# version spans carry real numeric versions (not the sglang literal default of a never-updated
# engine, with exemptions for debug and LoRA modes), the cap on rollouts served without a
# published weight version (derived from the update interval, floor of three, interval plus one),
# and the check that aborts a run whose version is never published. Module constant: the literal
# sglang default version string.
from argparse import Namespace

import pytest

from miles.utils.types import Sample, WeightVersionSpan, WeightVersionsPerCall
from miles.utils.weight_version import (
    SGLANG_DEFAULT_WEIGHT_VERSION,
    assert_samples_weight_version_sane,
    assert_weight_version_is_published,
    max_rollouts_without_published_weight_version,
)

SGLANG_LITERAL = "default"


def _make_args(**overrides: object) -> Namespace:
    # [FUNCTION DOC] HELPER: Builds an argument namespace with all debug flags off, no LoRA, and an
    # update weights interval of 1, then sets each override as an attribute. Returns it.
    args = Namespace(
        debug_rollout_only=False,
        debug_train_only=False,
        debug_skip_weight_update=False,
        lora_rank=0,
        lora_adapter_path=None,
        update_weights_interval=1,
    )
    for key, value in overrides.items():
        setattr(args, key, value)
    return args


def _make_sample(versions: list[str], index: int = 0) -> Sample:
    # [FUNCTION DOC] HELPER: Builds a sample with the given index whose tokens are 0 up to the
    # number of versions, response length equal to that, and one call record per version holding
    # one span of that version covering one token at position i (span i to i+1).
    calls = [
        WeightVersionsPerCall(spans=[WeightVersionSpan(version=version, abs_start=i, abs_end=i + 1)])
        for i, version in enumerate(versions)
    ]
    return Sample(
        index=index,
        tokens=list(range(len(versions))),
        response_length=len(versions),
        weight_versions=calls,
    )


def _simulate_rollouts_since_publish(*, update_weights_interval: int, num_rollout: int) -> list[int]:
    # [FUNCTION DOC] HELPER: Models a driver that prefetches one rollout ahead and publishes a
    # weight version after every interval-th rollout. For each rollout id it first fetches
    # rollouts up to that id (each fetch increments the since-publish counter and records it);
    # when (id+1) is a multiple of the interval it also prefetches the next rollout if any remain
    # (counter incremented and recorded) and then resets the counter to zero. Returns the recorded
    # counter values in fetch order.
    counts: list[int] = []
    rollouts_since_publish = 0
    next_get = 0
    for rollout_id in range(num_rollout):
        while next_get <= rollout_id:
            rollouts_since_publish += 1
            counts.append(rollouts_since_publish)
            next_get += 1
        if (rollout_id + 1) % update_weights_interval == 0:
            if next_get < num_rollout:
                rollouts_since_publish += 1
                counts.append(rollouts_since_publish)
                next_get += 1
            rollouts_since_publish = 0
    return counts


class TestAssertSamplesWeightVersionSane:
    # [CLASS DOC] Tests of the sample weight version span validation, which raises an assertion
    # error for spans with the sglang default or non numeric versions unless the run mode never
    # pushes weights.
    def test_the_guarded_literal_is_the_sglang_wire_value(self):
        # [FUNCTION DOC] The library's default version constant equals the string default.
        """sglang sends the literal 'default'; a drifted constant would let real default spans through."""
        assert SGLANG_DEFAULT_WEIGHT_VERSION == SGLANG_LITERAL

    def test_an_updated_engine_version_passes(self):
        # [FUNCTION DOC] A sample with the numeric version 3 passes.
        """Tokens generated after a weight update carry a real version and must be accepted."""
        assert_samples_weight_version_sane(_make_args(), samples=[_make_sample(["3"])])

    def test_multiple_numeric_weight_versions_pass(self):
        # [FUNCTION DOC] Versions 1, 2 and 10 in one sample pass.
        """A trajectory spanning several weight updates carries mixed numeric versions and must be accepted."""
        assert_samples_weight_version_sane(_make_args(), samples=[_make_sample(["1", "2", "10"])])

    def test_the_sglang_default_version_fails(self):
        # [FUNCTION DOC] A sample with the default version raises an assertion error saying the
        # engine was never updated.
        """Tokens generated by a never-updated engine must be rejected, not silently trained on."""
        with pytest.raises(AssertionError, match="never updated"):
            assert_samples_weight_version_sane(_make_args(), samples=[_make_sample([SGLANG_LITERAL])])

    def test_a_default_prefix_before_an_update_fails(self):
        # [FUNCTION DOC] Versions default then 1 still raise the never-updated error.
        """A request whose first tokens predate the first weight update must be caught despite later real versions."""
        with pytest.raises(AssertionError, match="never updated"):
            assert_samples_weight_version_sane(_make_args(), samples=[_make_sample([SGLANG_LITERAL, "1"])])

    def test_a_later_sample_with_a_trailing_foreign_version_fails(self):
        # [FUNCTION DOC] Two samples; the second (index 7) has a default version on its second
        # span. Asserts the error message names sample index 7 and the half-open token range from
        # 1 to 2 as generated under a foreign weight version.
        """Every sample and every span must be checked, not only the first sample or the first span."""
        samples = [_make_sample(["1", "2"], index=0), _make_sample(["3", SGLANG_LITERAL], index=7)]
        with pytest.raises(AssertionError, match=r"index=7 tokens \[1, 2\) were generated under weight version"):
            assert_samples_weight_version_sane(_make_args(), samples=samples)

    @pytest.mark.parametrize("version", ["mock-v0", "v3", "3.0", "-1", "", "3 "])
    def test_a_non_numeric_version_fails(self, version: str):
        # [FUNCTION DOC] Parametrized over mock-v0, v3, 3.0, -1, the empty string and a number
        # with a trailing space. Each raises an assertion error saying it is not the numeric
        # version.
        """miles stamps bare numeric versions, so anything else means the weights came from outside this run."""
        with pytest.raises(AssertionError, match="not the numeric version"):
            assert_samples_weight_version_sane(_make_args(), samples=[_make_sample([version])])

    def test_a_sample_without_spans_passes(self):
        # [FUNCTION DOC] A sample with no versions passes.
        """Samples with no recorded weight versions carry nothing to validate."""
        assert_samples_weight_version_sane(_make_args(), samples=[_make_sample([])])

    @pytest.mark.parametrize(
        "overrides",
        [
            {"debug_rollout_only": True},
            {"debug_skip_weight_update": True},
            {"lora_rank": 8},
            {"lora_adapter_path": "/adapters/foo"},
        ],
    )
    def test_modes_that_never_push_weights_are_exempt(self, overrides: dict[str, object]):
        # [FUNCTION DOC] Parametrized over rollout-only debug, skipped weight update, a LoRA rank
        # and a LoRA adapter path; a sample with the default version passes in each.
        """Debug modes and LoRA legitimately serve un-updated weights, so the default version is allowed."""
        assert_samples_weight_version_sane(_make_args(**overrides), samples=[_make_sample([SGLANG_LITERAL])])


class TestMaxRolloutsWithoutPublishedWeightVersion:
    # [CLASS DOC] Tests of the cap function: maximum of three and interval plus one.
    @pytest.mark.parametrize("update_weights_interval", [1, 2])
    def test_a_fast_cadence_keeps_the_floor_of_three(self, update_weights_interval: int):
        # [FUNCTION DOC] Intervals 1 and 2 give a cap of 3.
        """A cadence faster than the floor must not shrink the cap below three tolerated rollouts."""
        args = _make_args(update_weights_interval=update_weights_interval)

        assert max_rollouts_without_published_weight_version(args) == 3

    @pytest.mark.parametrize(
        ("update_weights_interval", "expected_cap"),
        [(3, 4), (4, 5), (8, 9), (100, 101)],
    )
    def test_a_slow_cadence_leaves_room_for_one_prefetched_rollout(
        self, update_weights_interval: int, expected_cap: int
    ):
        # [FUNCTION DOC] Intervals 3, 4, 8, 100 give caps 4, 5, 9, 101 (interval plus one).
        """The driver publishes once per interval and prefetches one rollout ahead, so the cap is the interval plus one."""
        args = _make_args(update_weights_interval=update_weights_interval)

        assert max_rollouts_without_published_weight_version(args) == expected_cap

    def test_the_cap_never_shrinks_as_the_cadence_slows(self):
        # [FUNCTION DOC] Caps for intervals 1 to 16 are already in sorted (non decreasing) order.
        """A slower publish cadence can only tolerate more unpublished rollouts, never fewer."""
        caps = [
            max_rollouts_without_published_weight_version(_make_args(update_weights_interval=interval))
            for interval in range(1, 17)
        ]

        assert caps == sorted(caps)


class TestAssertWeightVersionIsPublished:
    # [CLASS DOC] Tests of the published-version check, which raises an assertion error
    # mentioning the set-weight-version call when the rollouts since the last publish exceed the
    # cap, except in modes that never publish.
    def test_a_freshly_published_version_passes(self):
        # [FUNCTION DOC] One rollout since publish passes.
        """The normal loop publishes a version every step, so the count resets to one rollout."""
        assert_weight_version_is_published(_make_args(), rollouts_since_publish=1)

    def test_a_short_gap_passes(self):
        # [FUNCTION DOC] Three rollouts since publish at interval 1 pass.
        """A fast cadence keeps the floor of three, so an ordinary reordering does not fail the run."""
        assert_weight_version_is_published(_make_args(), rollouts_since_publish=3)

    def test_a_frozen_version_fails(self):
        # [FUNCTION DOC] Four rollouts since publish at interval 1 raise the error.
        """A training script that never forwards the version silently disables staleness accounting."""
        with pytest.raises(AssertionError, match="set_weight_version"):
            assert_weight_version_is_published(_make_args(), rollouts_since_publish=4)

    def test_a_slow_update_cadence_widens_the_gap(self):
        # [FUNCTION DOC] At interval 3, 4 rollouts pass and 5 raise the error.
        """A run publishing every third rollout serves four unpublished rollouts by design."""
        args = _make_args(update_weights_interval=3)

        assert_weight_version_is_published(args, rollouts_since_publish=4)

        with pytest.raises(AssertionError, match="set_weight_version"):
            assert_weight_version_is_published(args, rollouts_since_publish=5)

    @pytest.mark.parametrize(
        ("update_weights_interval", "last_tolerated"),
        [(1, 3), (2, 3), (3, 4), (4, 5), (10, 11)],
    )
    def test_the_cadence_derived_cap_is_inclusive_and_the_next_rollout_aborts(
        self, update_weights_interval: int, last_tolerated: int
    ):
        # [FUNCTION DOC] Parametrized over interval and last tolerated count pairs (1 and 3, 2 and
        # 3, 3 and 4, 4 and 5, 10 and 11). The last tolerated count passes and one more raises.
        """At every cadence the last tolerated rollout passes and one more aborts, so the bound stays finite."""
        args = _make_args(update_weights_interval=update_weights_interval)

        assert_weight_version_is_published(args, rollouts_since_publish=last_tolerated)

        with pytest.raises(AssertionError, match="set_weight_version"):
            assert_weight_version_is_published(args, rollouts_since_publish=last_tolerated + 1)

    @pytest.mark.parametrize("update_weights_interval", [1, 2, 3, 4, 7, 16])
    def test_a_correctly_wired_run_survives_its_own_publish_cadence(self, update_weights_interval: int):
        # [FUNCTION DOC] Parametrized over intervals 1, 2, 3, 4, 7, 16. Simulates 64 rollouts of a
        # correct driver, asserts the maximum recorded count equals interval plus one, and that
        # every recorded count passes the check.
        """A run that publishes every interval rollouts and prefetches one ahead must not abort itself mid-training."""
        args = _make_args(update_weights_interval=update_weights_interval)
        counts = _simulate_rollouts_since_publish(update_weights_interval=update_weights_interval, num_rollout=64)

        assert max(counts) == update_weights_interval + 1

        for rollouts_since_publish in counts:
            assert_weight_version_is_published(args, rollouts_since_publish=rollouts_since_publish)

    @pytest.mark.parametrize(
        "overrides",
        [
            {"debug_rollout_only": True},
            {"debug_train_only": True},
            {"debug_skip_weight_update": True},
            {"lora_rank": 8},
            {"lora_adapter_path": "/adapters/foo"},
        ],
    )
    def test_modes_that_never_publish_a_version_are_exempt(self, overrides: dict[str, object]):
        # [FUNCTION DOC] Parametrized over rollout-only debug, train-only debug, skipped weight
        # update, LoRA rank and LoRA adapter path; 1000 rollouts since publish passes in each.
        """These modes legitimately never push weights, so a frozen version is expected."""
        assert_weight_version_is_published(_make_args(**overrides), rollouts_since_publish=1000)
